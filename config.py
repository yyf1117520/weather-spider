def region_of(city: str) -> str:
    """返回城市所属大区，未登记的城市归入"其他"。"""
    return CITY_REGION.get(city, "其他")


def code_of(city: str) -> str | None:
    """按城市名取代码；若用户直接传了 9 位数字代码则原样返回。"""
    if city.isdigit() and len(city) == 9:
        return city
    return CITY_CODES.get(city)


